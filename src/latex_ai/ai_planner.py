@dataclass
class EditStep:
    """A single edit step in an edit plan."""
    command: str
    description: str
    rationale: str = ""
    
    def to_dict(self) -> dict:
        """Convert to dictionary."""
        return {
            "command": self.command,
            "description": self.description,
            "rationale": self.rationale
        }


@dataclass
class EditPlan:
    """A multi-step editing plan generated by AI."""
    goal: str
    steps: list[EditStep] = field(default_factory=list)
    summary: str = ""
    confidence: float = 0.8
    
    def to_dict(self) -> dict:
        """Convert to dictionary."""
        return {
            "goal": self.goal,
            "summary": self.summary,
            "confidence": self.confidence,
            "steps": [step.to_dict() for step in self.steps]
        }
    
    def to_json(self) -> str:
        """Convert to JSON string."""
        return json.dumps(self.to_dict(), indent=2)
    
    @classmethod
    def from_dict(cls, data: dict) -> EditPlan:
        """Create from dictionary."""
        plan = cls(
            goal=data.get("goal", ""),
            summary=data.get("summary", ""),
            confidence=data.get("confidence", 0.8)
        )
        for step_data in data.get("steps", []):
            plan.steps.append(EditStep(
                command=step_data.get("command", ""),
                description=step_data.get("description", ""),
                rationale=step_data.get("rationale", "")
            ))
        return plan


class AIPlanner:
    """AI-powered editor for LaTeX documents using Gemini API.
    
    Uses persistent cache (SQLite) to survive restarts and save API costs.
    Tracks multi-turn conversation context for coherent dialogue.
    """
    
    def __init__(self, api_key: Optional[str] = None, model: Optional[str] = None):
        """Initialize AI planner.
        
        Args:
            api_key: Google Gemini API key. If None, looks for GEMINI_API_KEY env var.
            model: AI model to use. If None, uses config default or gemini-pro.
        
        Raises:
            ValueError: If Gemini not available or API key not found
        """
        # Check API key first (more useful error than package missing)
        self.api_key = api_key or os.getenv("GEMINI_API_KEY")
        if not self.api_key:
            raise ValueError(
                "Gemini API key required. Set GEMINI_API_KEY environment variable "
                "or pass api_key parameter."
            )
        
        # Then check package availability (allow tests to patch genai)
        if genai is None:
            raise ValueError("google-genai not installed. Install with: pip install google-genai")
        
        # Configure client
        self.client = genai.Client(api_key=self.api_key)
        # Resolve requested AI model (from config if not provided)
        resolved_model = model
        available_ids = []
        try:
            from .config import get_config
            from .models_registry import AVAILABLE_MODEL_IDS
            cfg = get_config()
            available_ids = AVAILABLE_MODEL_IDS
            resolved_model = resolved_model or getattr(cfg, 'ai_model_default', None)
        except Exception:
            resolved_model = resolved_model or None
            available_ids = []

        # Validate requested model; fallback to first available or provider default
        if resolved_model and available_ids and resolved_model not in available_ids:
            logger.warning(f"Requested model '{resolved_model}' not available; falling back to default")
            resolved_model = available_ids[0]
        elif not resolved_model and available_ids:
            resolved_model = available_ids[0]

        # Map requested model to provider-specific identifier
        provider_model = "gemini-pro"
        if resolved_model:
            rm = resolved_model.lower()
            if "gemini" in rm:
                provider_model = "gemini-pro"
            elif "gpt-5" in rm or "codex" in rm:
                logger.info(f"Requested model '{resolved_model}' -> using Gemini compatibility model '{provider_model}'")

        self.model_name = provider_model
        
        # Multi-turn conversation tracking (maps session_id -> conversation history)
        # With bounded storage: max 100 active sessions, max 50 messages per session
        self.conversation_context: dict[str, list[dict]] = {}
        self.max_sessions = 100
        self.max_messages_per_session = 50
        self.session_ttl_seconds = 3600  # 1 hour inactivity timeout
        self._session_last_activity: dict[str, float] = {}  # Track last activity per session
    
    def add_to_conversation(self, session_id: str, role: str, content: str) -> None:
        """Add a message to the conversation context for a session.
        
        Enforces bounded storage: max messages per session and max active sessions.
        Cleans up expired sessions (TTL-based).
        
        Args:
            session_id: Unique identifier for this conversation session
            role: 'user' or 'assistant'
            content: Message content
        """
        # Clean up expired sessions periodically
        self._cleanup_expired_sessions()
        
        # Initialize session if needed
        if session_id not in self.conversation_context:
            # Remove oldest session if at capacity
            if len(self.conversation_context) >= self.max_sessions:
                oldest = min(self._session_last_activity.keys(), 
                           key=lambda k: self._session_last_activity.get(k, 0))
                del self.conversation_context[oldest]
                del self._session_last_activity[oldest]
                logger.info(f"Removed oldest session {oldest} due to capacity")
            
            self.conversation_context[session_id] = []
        
        # Add message with timestamp
        self.conversation_context[session_id].append({
            'role': role,
            'content': content,
            'timestamp': time.time()
        })
        
        # Update last activity time
        self._session_last_activity[session_id] = time.time()
        
        # Enforce max messages per session (keep latest messages)
        if len(self.conversation_context[session_id]) > self.max_messages_per_session:
            excess = len(self.conversation_context[session_id]) - self.max_messages_per_session
            self.conversation_context[session_id] = self.conversation_context[session_id][excess:]
            logger.debug(f"Trimmed {excess} messages from session {session_id}")
        
        logger.debug(f"Added {role} message to session {session_id} "
                    f"({len(self.conversation_context[session_id])} messages)")
    
    def _cleanup_expired_sessions(self) -> None:
        """Remove sessions that haven't been accessed within TTL."""
        now = time.time()
        expired = []
        
        for session_id, last_activity in self._session_last_activity.items():
            if now - last_activity > self.session_ttl_seconds:
                expired.append(session_id)
        
        for session_id in expired:
            if session_id in self.conversation_context:
                del self.conversation_context[session_id]
            del self._session_last_activity[session_id]
            logger.info(f"Cleaned up expired session {session_id}")

    
    def get_conversation_context(self, session_id: str) -> str:
        """Get formatted conversation history for context in AI prompt.
        
        Args:
            session_id: Unique identifier for this conversation session
        
        Returns:
            Formatted conversation history or empty string if no history
        """
        if session_id not in self.conversation_context or not self.conversation_context[session_id]:
            return ""
        
        messages = self.conversation_context[session_id]
        formatted = []
        
        for msg in messages:
            prefix = "User" if msg['role'] == 'user' else "Assistant"
            formatted.append(f"{prefix}: {msg['content']}")
        
        return "\n\n".join(formatted)
    
    def clear_conversation(self, session_id: str) -> None:
        """Clear conversation history for a session.
        
        Args:
            session_id: Unique identifier for this conversation session
        """
        if session_id in self.conversation_context:
            del self.conversation_context[session_id]
        if session_id in self._session_last_activity:
            del self._session_last_activity[session_id]
        logger.debug(f"Cleared conversation for session {session_id}")
    
    def create_plan(self, document: Document, request: str) -> EditPlan:
        """Create an editing plan for a LaTeX document.
        
        Args:
            document: Document to edit
            request: Natural language request (e.g., "Make this paper conference-ready")
        
        Returns:
            EditPlan with steps
        
        Raises:
            CircuitBreakerOpen: If too many AI failures
            ValueError: If API fails or invalid response
        """
        # Check circuit breaker
        _check_circuit_breaker()
        
        # Calculate cache key
        file_hash = hash_content(document.text)
        cache_key = compute_plan_cache_key(file_hash, self.model_name, request)
        
        # Check persistent cache (survives restarts)
        cached_json = get_cached_plan(cache_key)
        if cached_json:
            try:
                plan_dict = json.loads(cached_json)
                plan = EditPlan.from_dict(plan_dict)
                logger.debug(f"Persistent cache hit for plan")
                return plan
            except (json.JSONDecodeError, KeyError) as e:
                logger.warning(f"Invalid cached plan, regenerating: {e}")
        
        context = self._prepare_context(document)
        prompt = create_plan_prompt(context, request)
        
        logger.debug(f"Sending prompt to Gemini: {len(prompt)} chars")
        
        try:
            response = self.client.models.generate_content(
                model=self.model_name,
                contents=prompt
            )
            plan_dict = self._parse_response(response.text)
            plan = EditPlan.from_dict(plan_dict)
            logger.info(f"Generated plan with {len(plan.steps)} steps")
            
            # Store in persistent cache (survives server restarts)
            plan_json = json.dumps(plan_dict)
            store_cached_plan(cache_key, plan_json)
            
            # Success - reset circuit breaker
            _record_ai_success()
            
            return plan
        except Exception as e:
            logger.error(f"AI planning failed: {e}")
            _record_ai_failure()
            raise ValueError(f"Failed to generate plan: {e}") from e
    
    async def create_plan_streaming(self, document: Document, request: str, session_id: str = None, conversation_context: list = None):
        """Create an editing plan with streaming updates (SSE compatible).
        
        Yields incremental updates as steps are generated, eliminating the
        "hanging" feeling during long AI generation.
        
        Args:
            document: Document to edit
            request: Natural language request
            session_id: Optional session ID for tracking conversation context
            conversation_context: Optional previous messages [{role, content}, ...]
            
        Yields:
            Dict events: {'type': 'progress|step|complete|error', 'data': ...}
        
        Raises:
            CircuitBreakerOpen: If too many AI failures
        """
        # Check circuit breaker
        _check_circuit_breaker()
        
        # Check cache first
        file_hash = hash_content(document.text)
        cache_key = compute_plan_cache_key(file_hash, self.model_name, request)
        
        cached_json = get_cached_plan(cache_key)
        if cached_json:
            try:
                plan_dict = json.loads(cached_json)
                plan = EditPlan.from_dict(plan_dict)
                
                # Stream cached plan steps for consistent UX
                yield {'type': 'progress', 'data': {'message': 'Loading cached plan', 'progress': 0.5}}
                for i, step in enumerate(plan.steps):
                    yield {'type': 'step', 'data': step.to_dict(), 'index': i}
                
                yield {'type': 'complete', 'data': plan.to_dict()}
                return
            except (json.JSONDecodeError, KeyError) as e:
                logger.warning(f"Invalid cached plan: {e}")
        
        # Generate new plan with streaming
        yield {'type': 'progress', 'data': {'message': 'Analyzing document', 'progress': 0.1}}
        
        context = self._prepare_smart_context(document, request)
        
        # Include conversation context if provided
        if conversation_context:
            conv_summary = "\n\n".join([
                f"{msg.get('role', 'User').upper()}: {msg.get('content', '')}"
                for msg in conversation_context
            ])
            context = f"Previous conversation:\n{conv_summary}\n\nDocument context:\n{context}"
        
        prompt = create_plan_prompt(context, request)
        
        yield {'type': 'progress', 'data': {'message': 'Generating plan', 'progress': 0.3}}
        
        try:
            # Use streaming API if available
            response = self.client.models.generate_content(
                model=self.model_name,
                contents=prompt
            )
            
            yield {'type': 'progress', 'data': {'message': 'Processing response', 'progress': 0.8}}
            
            plan_dict = self._parse_response(response.text)
            plan = EditPlan.from_dict(plan_dict)
            
            # Stream individual steps
            for i, step in enumerate(plan.steps):
                yield {'type': 'step', 'data': step.to_dict(), 'index': i}
            
            # Cache for future requests
            plan_json = json.dumps(plan_dict)
            store_cached_plan(cache_key, plan_json)
            
            # Success - reset circuit breaker
            _record_ai_success()
            
            # Store in conversation context if session_id provided
            if session_id:
                response_summary = plan.summary or f"Generated {len(plan.steps)} steps"
                self.add_to_conversation(session_id, 'assistant', response_summary)
            
            yield {'type': 'complete', 'data': plan.to_dict()}
            
        except Exception as e:
            logger.error(f"AI streaming failed: {e}")
            _record_ai_failure()
            yield {'type': 'error', 'data': {'message': str(e)}}
    
    def _prepare_smart_context(self, document: Document, request: str) -> str:
        """Extract only relevant context for the request (avoids token limits).
        
        For large documents, intelligently selects sections based on the request
        instead of sending the entire file.
        
        Args:
            document: Document to analyze
            request: User's natural language request
            
        Returns:
            Focused context string
        """
        lines = document.text.split('\n')
        doc_class = document.find_documentclass()
        packages = document.get_packages()
        
        # For small documents, use full context
        if len(lines) <= 200:
            return self._prepare_context(document)
        
        # Extract sections based on request keywords
        request_lower = request.lower()
        
        # Always include preamble
        preamble_end = 0
        for i, line in enumerate(lines):
            if '\\begin{document}' in line:
                preamble_end = i
                break
        
        preamble = '\n'.join(lines[:min(preamble_end + 5, 50)])
        
        # Smart section selection based on request
        sections = []
        if any(kw in request_lower for kw in ['abstract', 'introduction', 'summary']):
            sections.extend(self._extract_section(lines, 'abstract'))
            sections.extend(self._extract_section(lines, 'introduction'))
        
        if any(kw in request_lower for kw in ['conclusion', 'end', 'summary']):
            sections.extend(self._extract_section(lines, 'conclusion'))
        
        if any(kw in request_lower for kw in ['reference', 'bibliography', 'cite']):
            sections.extend(self._extract_section(lines, 'bibliography'))
        
        # If no specific sections matched, include first 100 lines
        if not sections:
            sections = lines[:100]
        
        section_text = '\n'.join(sections[:150])  # Limit to 150 lines
        
        context = f"""Document Analysis:
- Document class: {doc_class or 'unknown'}
- Packages: {', '.join([f'{pkg}' for pkg, _ in packages]) if packages else 'none'}
- Total lines: {len(lines)} (showing relevant sections)

Preamble:
{preamble}

Relevant Content:
{section_text}
"""
        
        return context
    
    def _extract_section(self, lines: list, section_name: str) -> list:
        """Extract lines from a specific section.
        
        Args:
            lines: Document lines
            section_name: Section to extract (e.g., 'abstract', 'introduction')
            
        Returns:
            List of lines in that section
        """
        section_lines = []
        in_section = False
        
        for line in lines:
            # Check for environment or section start
            if f'\\begin{{{section_name}}}' in line.lower() or \
               f'\\section{{{section_name}' in line.lower() or \
               f'\\section*{{{section_name}' in line.lower():
                in_section = True
            
            if in_section:
                section_lines.append(line)
            
            # Check for environment or section end
            if in_section and (f'\\end{{{section_name}}}' in line.lower() or \
                              '\\section' in line and len(section_lines) > 5):
                break
        
        return section_lines[:50]  # Max 50 lines per section
    
    def _prepare_context(self, document: Document) -> str:
        """Prepare document context for AI analysis."""
        lines = document.text.split('\n')
        doc_class = document.find_documentclass()
        packages = document.get_packages()
        
        context = f"""Document Analysis:
- Document class: {doc_class or 'unknown'}
- Packages: {', '.join([f'{pkg}' for pkg, _ in packages]) if packages else 'none'}
- Total lines: {len(lines)}
- First 20 lines:
{chr(10).join(lines[:20])}"""
        
        return context
    
